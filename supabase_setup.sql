-- ============================================================
-- 12. カレンダー取り込み用 SQL 関数 import_kintai_rows
--     画面（index.html の importGcalRecords）から rpc で 1 回呼ぶ。
--     「取り込む日付の自分の行を消す → 選んだ行を追加する」を 1 つのトランザクションで行い、
--     途中で失敗したら消した分も含めて全部取り消す。
--     ・SECURITY INVOKER（本人の権限で動く）。RLS・列ごとの権限（10.）・NOT NULL・CHECK（0-2.）がそのまま効く
--     ・user_id は auth.uid() を使い、画面からは受け取らない
--     ・work_min は受け取らず、INSERT もしない。INSERT 時に DB のトリガー（13.）が計算して入れる
--       （行データに work_min の key があっても読み飛ばす）
--     ・追加した行数を返す
--     既存環境への初回反映・確認・戻し方は
--     supabase/migrations/20261117_kintai_import_rpc.sql と
--     supabase/migrations/20261118_kintai_work_min_cleanup_1.sql（work_min を受け取らない形に変更）を参照
-- ============================================================
CREATE OR REPLACE FUNCTION public.import_kintai_rows(p_rows jsonb)
RETURNS integer
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_uid   uuid := auth.uid();
  v_count integer;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'ログインしていません。再ログインしてください'
      USING ERRCODE = '42501';
  END IF;

  -- OR の評価順は決まっていないため、配列かどうかを確かめてから長さを見る
  IF p_rows IS NULL OR jsonb_typeof(p_rows) <> 'array' THEN
    RAISE EXCEPTION '取り込む行の形式が正しくありません（配列ではありません）'
      USING ERRCODE = '22023';
  END IF;
  IF jsonb_array_length(p_rows) = 0 THEN
    RAISE EXCEPTION '取り込む行がありません'
      USING ERRCODE = '22023';
  END IF;

  -- 取り込む日付の自分の行を消す
  DELETE FROM public.kintai AS k
  WHERE k.user_id = v_uid
    AND k.date IN (
      SELECT r.date
      FROM jsonb_to_recordset(p_rows) AS r(date text)
    );

  -- 追加する（列の型は kintai の定義に合わせる。user_id は auth.uid()）
  -- 勤務時間は kintai の BEFORE INSERT トリガーが計算して入れる。
  -- 行データに勤務時間の key があっても、下の列の定義にないので読み飛ばす
  INSERT INTO public.kintai (date, start_time, end_time, break_min, memo, user_id)
  SELECT r.date, r.start_time, r.end_time, r.break_min, r.memo, v_uid
  FROM jsonb_to_recordset(p_rows) AS r(
    date       text,
    start_time text,
    end_time   text,
    break_min  integer,
    memo       text
  );

  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

REVOKE ALL ON FUNCTION public.import_kintai_rows(jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.import_kintai_rows(jsonb) TO authenticated;

-- ============================================================
-- 13. 勤務時間（work_min）を DB で計算するトリガー
--     ・work_min ＝ 退勤 − 出勤 − 休憩（分）。退勤が出勤より前なら翌日の退勤として +1440 分
--     ・画面・取り込みから渡された work_min は使わず、計算結果で上書きする
--     ・エラー（コード 23514。メッセージの名前で画面が見分ける）:
--         出勤と退勤が同じ時刻       … kintai_work_min_same_time_chk
--         計算結果が 0 以下          … kintai_work_min_positive_chk
--         計算結果が 720 分を超える   … kintai_work_min_max_chk
--       ※ この 3 つは本物の CHECK 制約ではなく、エラーの見分け用の名前
--     ・時刻の形が不正・休憩が NULL かマイナスのときは計算せずに通し、
--       0-2. の CHECK 制約・NOT NULL のエラーに任せる。
--       このとき work_min が NULL（送られていない）なら 0 を入れる
--       （NOT NULL は CHECK 制約より先に確かめられるため、0 を入れないと
--         「work_min が NULL」（23502）が先に出て、休憩・時刻の CHECK 制約のエラーにならない）
--     ・UPDATE は start_time / end_time / break_min / work_min を含むときだけ動く
--       （slack_reported_at だけ・memo だけの更新では動かない）
--     ・トリガー関数は PUBLIC・anon・authenticated から EXECUTE を外す
--       （トリガーとして呼ばれるときは EXECUTE 権限を確かめない）
--     既存環境への初回反映・確認・戻し方は
--     supabase/migrations/20261117_kintai_work_min_trigger.sql と
--     supabase/migrations/20261118_kintai_work_min_cleanup_1.sql（work_min が NULL なら 0 を入れる変更）を参照
-- ============================================================
CREATE OR REPLACE FUNCTION public.kintai_compute_work_min()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_span integer;  -- 退勤 − 出勤（分。日またぎは +1440）
  v_work integer;  -- v_span − 休憩
BEGIN
  -- 形が不正・休憩が NULL かマイナスなら計算しない（今の CHECK 制約・NOT NULL のエラーに任せる）
  IF NEW.start_time IS NULL OR NEW.end_time IS NULL OR NEW.break_min IS NULL
     OR NEW.start_time !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'
     OR NEW.end_time   !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'
     OR NEW.break_min < 0 THEN
    -- work_min が送られていなくても、NOT NULL（23502）より先に
    -- 休憩・時刻の CHECK 制約（23514）のエラーが出るよう 0 を入れる
    NEW.work_min := coalesce(NEW.work_min, 0);
    RETURN NEW;
  END IF;

  v_span := (substr(NEW.end_time,   1, 2)::int * 60 + substr(NEW.end_time,   4, 2)::int)
          - (substr(NEW.start_time, 1, 2)::int * 60 + substr(NEW.start_time, 4, 2)::int);
  IF v_span < 0 THEN
    v_span := v_span + 1440;  -- 退勤が出勤より前 → 翌日の退勤
  END IF;

  IF v_span = 0 THEN
    RAISE EXCEPTION '出勤と退勤が同じ時刻です（kintai_work_min_same_time_chk）'
      USING ERRCODE = '23514', CONSTRAINT = 'kintai_work_min_same_time_chk';
  END IF;

  v_work := v_span - NEW.break_min;

  IF v_work <= 0 THEN
    RAISE EXCEPTION '休憩が勤務時間（%分）以上です（kintai_work_min_positive_chk）', v_span
      USING ERRCODE = '23514', CONSTRAINT = 'kintai_work_min_positive_chk';
  END IF;

  IF v_work > 720 THEN
    RAISE EXCEPTION '勤務時間が12時間を超えています（休憩を除いて%分）（kintai_work_min_max_chk）', v_work
      USING ERRCODE = '23514', CONSTRAINT = 'kintai_work_min_max_chk';
  END IF;

  NEW.work_min := v_work;  -- 画面から渡された値は使わない
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.kintai_compute_work_min() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS kintai_compute_work_min ON public.kintai;
CREATE TRIGGER kintai_compute_work_min
  BEFORE INSERT OR UPDATE OF start_time, end_time, break_min, work_min ON public.kintai
  FOR EACH ROW EXECUTE FUNCTION public.kintai_compute_work_min();

-- ============================================================
-- 14. 月の締め（本人が提出 → 管理者が承認・差し戻し。承認前は本人が取り下げ）
--     ・1人×暦月で1件（kintai_closing）。対象は 2026年11月分から。締められるのは日本時間で翌月1日以降
--     ・勤怠が0件の月・作業内容が空（空白だけを含む）の行がある月は締められない。勤務日数は日付の重複を除く
--     ・承認時に集計を計算し直し、単価（profiles.inv_rate。NULL・0以下はエラー）と
--       金額（勤務時間 × 単価 の切り捨て。税抜）を保存する
--     ・管理者は自分の締めを承認・差し戻しできない。承認後の差し戻しも管理者だけ
--     ・提出済・承認済の月は、その人の kintai を追加・編集・削除できない（トリガー kintai_block_closed_month。
--       取り込み・SQL Editor も含む。Slack 報告の印だけの更新は通す。日付を変える編集は前後両方の月を確かめる）
--     ・提出・取り下げ・承認・差し戻しとトリガーは、user_id と月の advisory lock で同時実行をそろえる
--     ・履歴は kintai_closing_log（authenticated からは見えない。SQL Editor で見る）
--     ・処理の本体は private の関数（あとで別システムからも使えるよう、操作する人・今日を引数で受け取る）。
--       画面は public の submit / withdraw / approve / return_kintai_closing を rpc で呼ぶ
--     ・新しいテーブル・自動採番・関数から PUBLIC・anon の権限を外す（service_role は Supabase の既定のまま）
--     ・トリガーは名前の順で動くため、kintai_compute_work_min（13.）より先に締めを確かめる
--     既存環境への初回反映・確認・戻し方は
--     supabase/migrations/20261119_kintai_closing.sql を参照
--     （エラーの名前の一覧も移行 SQL の冒頭にある）
-- ============================================================
