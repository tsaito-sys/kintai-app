-- 0-1. private スキーマと日付判定関数（kintai の date の CHECK 制約で使う）
--    ・private は API（PostgREST）に公開しないスキーマ
--      （Dashboard > Settings > API の Exposed schemas に足さないこと）
--    ・CHECK 制約の関数は「書き込んだユーザーの権限」で実行されるため、
--      kintai に書き込む authenticated と service_role にだけ USAGE / EXECUTE を付ける
CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC, anon;
GRANT USAGE ON SCHEMA private TO authenticated, service_role;

-- 'YYYY-MM-DD' の形で、実在する日付なら true（NULL・空文字・13月・2月30日・0000年などは false）
--   ・CASE で順に確かめるので、形が違う値で型変換エラーにはならない
--   ・数字は [0-9]（全角数字などは通さない）
CREATE OR REPLACE FUNCTION private.is_valid_ymd(p text)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = ''
AS $$
  SELECT CASE
    WHEN p IS NULL THEN false
    WHEN p !~ '^[0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01])$' THEN false
    WHEN substr(p, 1, 4)::int < 1 THEN false
    ELSE substr(p, 9, 2)::int
         <= extract(day FROM make_date(substr(p, 1, 4)::int, substr(p, 6, 2)::int, 1)
                             + interval '1 month - 1 day')::int
  END
$$;

REVOKE ALL ON FUNCTION private.is_valid_ymd(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION private.is_valid_ymd(text) TO authenticated, service_role;

-- 0-2. kintai テーブル
CREATE TABLE IF NOT EXISTS public.kintai (
  id                bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  date              text NOT NULL,
  start_time        text NOT NULL,
  end_time          text NOT NULL,
  break_min         integer NOT NULL,
  work_min          integer NOT NULL,
  memo              text NOT NULL,
  user_id           uuid NOT NULL,
  slack_reported_at timestamptz,
  CONSTRAINT kintai_pkey         PRIMARY KEY (id),
  CONSTRAINT kintai_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users(id),
  CONSTRAINT kintai_date_format_chk
    CHECK (private.is_valid_ymd(date)),
  CONSTRAINT kintai_start_time_format_chk
    CHECK (start_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  CONSTRAINT kintai_end_time_format_chk
    CHECK (end_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  CONSTRAINT kintai_break_min_nonneg_chk
    CHECK (break_min >= 0),
  CONSTRAINT kintai_work_min_nonneg_chk
    CHECK (work_min >= 0)
);

