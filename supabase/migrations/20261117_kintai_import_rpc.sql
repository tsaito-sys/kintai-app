-- ============================================================
-- カレンダー取り込みを 1 つのトランザクションにまとめる
--   public.import_kintai_rows(p_rows jsonb) を作る
--
--   今まで画面（index.html の importGcalRecords）は
--     1. delete … 取り込む日付の自分の行を消す
--     2. insert … 選んだ行を追加する
--   を別々のリクエストで送っていたため、2 が失敗すると 1 で消した行が戻らなかった。
--   この関数を rpc で 1 回呼ぶ形にし、途中で失敗したら消した分も含めて全部取り消す。
--
--   関数の動き:
--     ・auth.uid() が NULL（ログインしていない）ならエラー
--     ・p_rows が配列でない、または空ならエラー
--     ・user_id = auth.uid() かつ p_rows の日付に当たる行を消す
--       （同じ日の自分の行は、手で入力した行も含めて消す。今までの動きと同じ）
--     ・p_rows の行を追加する。user_id は auth.uid() を使い、画面からは受け取らない
--       追加する列: date, start_time, end_time, break_min, work_min, memo
--       （work_min は画面で計算した値をそのまま使う）
--     ・追加した行数を返す
--   SECURITY INVOKER（呼んだ本人の権限で動く）なので、
--   RLS・列ごとの権限・NOT NULL・CHECK 制約はそのまま効く。
--   制約に合わない行が 1 つでもあれば、関数全体がエラーになり何も変わらない。
--
-- 本人（authenticated）の権限で動くことの確認（2026-11-17、supabase_setup.sql の定義から）:
--   DELETE   … テーブル単位の DELETE あり。RLS kintai_delete（auth.uid() = user_id）
--              WHERE で列を読むための SELECT もあり（RLS kintai_select で自分の行は見える）
--   INSERT   … 列ごとの INSERT（date, start_time, end_time, break_min, work_min, memo, user_id）あり。
--              関数が追加する列はこの 7 列だけ。RLS kintai_insert（auth.uid() = user_id）
--   id       … GENERATED BY DEFAULT AS IDENTITY。IDENTITY の採番は kintai_id_seq の権限を確かめない
--              （PostgreSQL の仕様）。念のため authenticated には USAGE / SELECT / UPDATE も付いている
--   CHECK    … private.is_valid_ymd は authenticated に USAGE / EXECUTE が付いている
--   → 足りない権限はない
--
-- 実行権限:
--   PUBLIC と anon から外し、authenticated に付ける。
--   ※ Supabase の初期設定で service_role（と所有者の postgres）にも EXECUTE が付く。
--     service_role から呼んでも auth.uid() が NULL なのでエラーで止まる。
--
-- 実行方法:
--   Supabase Dashboard > SQL Editor にこのファイル全体を貼り、まとめて 1 回実行する。
--   BEGIN〜COMMIT で囲んであるので、途中でエラーになったら全部取り消される。
--   ※ 画面（index.html の rpc 呼び出し）を公開する「前」に実行すること。
--     関数がないと取り込みが「取り込み失敗」になる（行は消えない）。
--
-- 実行後の確認: supabase/checks/kintai_import_rpc_verify.sql
-- 戻す場合    : supabase/rollbacks/20261117_kintai_import_rpc_rollback.sql
-- ============================================================

BEGIN;

-- 他の処理がテーブルを掴んでいたら、待ち続けずにエラーで止める
SET LOCAL lock_timeout = '5s';


-- ------------------------------------------------------------
-- 1. 関数
--    ・CREATE OR REPLACE は付けない（既にあればエラーで止める）
--    ・search_path = '' なので、テーブル・関数はスキーマ名つきで書く
--      （jsonb_* などの組み込み関数は pg_catalog なので不要）
-- ------------------------------------------------------------
CREATE FUNCTION public.import_kintai_rows(p_rows jsonb)
RETURNS integer
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_uid   uuid := auth.uid();
  v_count integer;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'ログインしていません。再ログインしてください'
      USING ERRCODE = '42501';
  END IF;

  -- OR の評価順は決まっていないため、配列かどうかを確かめてから長さを見る
  IF p_rows IS NULL OR jsonb_typeof(p_rows) <> 'array' THEN
    RAISE EXCEPTION '取り込む行の形式が正しくありません（配列ではありません）'
      USING ERRCODE = '22023';
  END IF;
  IF jsonb_array_length(p_rows) = 0 THEN
    RAISE EXCEPTION '取り込む行がありません'
      USING ERRCODE = '22023';
  END IF;

  -- 取り込む日付の自分の行を消す
  DELETE FROM public.kintai AS k
  WHERE k.user_id = v_uid
    AND k.date IN (
      SELECT r.date
      FROM jsonb_to_recordset(p_rows) AS r(date text)
    );

  -- 追加する（列の型は kintai の定義に合わせる。user_id は auth.uid()）
  INSERT INTO public.kintai (date, start_time, end_time, break_min, work_min, memo, user_id)
  SELECT r.date, r.start_time, r.end_time, r.break_min, r.work_min, r.memo, v_uid
  FROM jsonb_to_recordset(p_rows) AS r(
    date       text,
    start_time text,
    end_time   text,
    break_min  integer,
    work_min   integer,
    memo       text
  );

  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;


-- ------------------------------------------------------------
-- 2. 実行権限
-- ------------------------------------------------------------
REVOKE ALL ON FUNCTION public.import_kintai_rows(jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.import_kintai_rows(jsonb) TO authenticated;

COMMIT;
